/* USER CODE BEGIN 4 */
void Read_Environment(void)
{
    /* Start ADC conversion sequence */
    HAL_ADC_Start(&hadc1);

    /* Rank 1 = ADC Channel 0 = Turbidity */
    HAL_ADC_PollForConversion(&hadc1, 1000);

    turbidity_adc = HAL_ADC_GetValue(&hadc1);

    /* Rank 2 = ADC Channel 1 = Ambient Noise */
    HAL_ADC_PollForConversion(&hadc1, 1000);

    noise_adc = HAL_ADC_GetValue(&hadc1);

    HAL_ADC_Stop(&hadc1);

    /* Convert ADC values 0-4095 into percentage */

    turbidity_percent =
        ((float)turbidity_adc / 4095.0f) * 100.0f;

    noise_percent =
        ((float)noise_adc / 4095.0f) * 100.0f;
}

void Adaptive_Frequency_Algorithm(void)
{
    /*
     * Environmental Difficulty Score
     *
     * Turbidity = 60% importance
     * Noise     = 40% importance
     */

    difficulty =
        (0.6f * turbidity_percent) +
        (0.4f * noise_percent);


    if (difficulty < 33.0f)
    {
        selected_frequency =
            FREQ_LOW_DIFFICULTY;       // 30 kHz
    }

    else if (difficulty < 66.0f)
    {
        selected_frequency =
            FREQ_MEDIUM_DIFFICULTY;    // 25 kHz
    }

    else
    {
        selected_frequency =
            FREQ_HIGH_DIFFICULTY;      // 20 kHz
    }
}

void Set_Sonar_Frequency(uint32_t frequency)
{
    uint32_t sample_rate;
    uint32_t timer_clock;
    uint32_t timer_period;

    /*
     * One complete sine wave contains 32 samples
     */

    sample_rate =
        frequency * SINE_SAMPLES;


    /*
     * Your current TIM2 clock = 16 MHz
     */

    timer_clock = 16000000;


    /*
     * Timer equation:
     *
     * F_update =
     *
     * Timer_Clock
     * --------------------
     * (PSC+1)(ARR+1)
     *
     * PSC = 0
     *
     * Therefore:
     *
     * ARR =
     *
     * Timer_Clock
     * ---------------- - 1
     * Sample_Rate
     */

    timer_period =
        (timer_clock / sample_rate) - 1;


    /* Stop TIM2 before changing frequency */

    HAL_TIM_Base_Stop(&htim2);


    /* Set new Auto Reload Register */

    __HAL_TIM_SET_AUTORELOAD(
        &htim2,
        timer_period
    );


    /* Reset counter */

    __HAL_TIM_SET_COUNTER(
        &htim2,
        0
    );


    /* Restart TIM2 */

    HAL_TIM_Base_Start(&htim2);
}
